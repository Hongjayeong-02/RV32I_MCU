#!/bin/bash
# make_pdk_setup_chip.sh : PDK lines for the chip-level P&R (M5), taken from the UART V3
# PADALL Innovus run already on this server, so no PDK path is written in PROJ2.
#   cd APR/scripts_chip ; bash make_pdk_setup_chip.sh [UART V3 PADALL P&R dir]
# writes (git-ignored) :
#   pdk_lef_chip.tcl   set PDK_STD ... ; set init_lef_file [std tech LEF, std macro LEF, PAD LEF]
#   pdk_mmmc_chip.tcl  RC corners + library sets (std cell + PAD lib, SS / FF)
cd "$(dirname "$0")" || exit 1
SRC=${1:-$HOME/PROJ1/proj1_make/TOP/PNR/PNR_10NS_PADALL_RO}
INIT=$SRC/0_InitDesign.tcl
MMMC=$(ls $SRC/*.mmmc.view 2>/dev/null | head -1)
for f in $INIT $MMMC; do
  [ -f "$f" ] || { echo "ERROR: $f not found (give the UART V3 PADALL P&R dir as argument)"; exit 1; }
  grep -q '<PDK>' "$f" && { echo "ERROR: $f has <PDK> placeholders"; exit 1; }
done
echo "INFO: PDK lines taken from $SRC"
{
  echo "# generated by make_pdk_setup_chip.sh from $SRC  -- DO NOT COMMIT"
  # every PDK variable the LEF list needs (e.g. set <PDK> ... ; set PDK_STD $<PDK>/...)
  grep -E '^set (G?PDK|GIO)[A-Za-z_0-9]* ' $INIT
  # init_lef_file statement (spans lines with \) ; a LEF given without a directory lives in $SRC
  awk '/^set init_lef_file/{p=1} p{print} p && !/\\$/{exit}' $INIT | sed -E "s#([[:space:][])([A-Za-z0-9_.]+\.lef)#\1$SRC/\2#g"
  # PDK stream map (Innovus format) for the design-only GDS (M5-5 merge) : taken from the
  # UART V3 merge script (stream_pdkmap.tcl) or any PROJ1 Tcl that uses streamOut -mapFile
  M=${MCU_STREAM_MAP:-$(grep -rhoE -- '-mapFile [^ ]+' $(find ~ -maxdepth 7 -name 'stream_pdkmap*.tcl' 2>/dev/null) \
      ~/PROJ1 --include='*.tcl' 2>/dev/null | grep -v '<PDK>' | awk '{print $2}' | head -1)}
  [ -n "$M" ] && [ -f "$M" ] || M=$(find /$(grep -m1 -E '^set (G?PDK)' $INIT | awk '{print $3}' | cut -d/ -f2) -name streamOut.map 2>/dev/null | head -1)
  [ -n "$M" ] && [ -f "$M" ] && echo "set STREAM_MAP $M" || echo "# STREAM_MAP not found : setenv MCU_STREAM_MAP <streamOut.map> and rerun"
} > pdk_lef_chip.tcl
{
  echo "# generated by make_pdk_setup_chip.sh from $MMMC  -- DO NOT COMMIT"
  awk '/create_delay_corner|Delay Corner/{exit} {print}' $MMMC
} > pdk_mmmc_chip.tcl
grep -oE '[^ /[]+\.lef' pdk_lef_chip.tcl | sed 's/^/LEF  /'
grep -c '^create_rc_corner\|^create_library_set' pdk_mmmc_chip.tcl | sed 's/^/rc corners + library sets : /'
grep -q '^set STREAM_MAP' pdk_lef_chip.tcl && echo "stream map : $(basename $(awk '/^set STREAM_MAP/{print $3}' pdk_lef_chip.tcl))" \
  || echo "WARNING: stream map not found (needed for M5-5 only) : setenv MCU_STREAM_MAP <streamOut.map>"
echo "INFO: wrote pdk_lef_chip.tcl, pdk_mmmc_chip.tcl"
