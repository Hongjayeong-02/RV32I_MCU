#!/usr/bin/env python3
"""
gen_rand_test.py : random instruction stream for the core (spec 12, hazard coverage)

  - registers x1..x12 only -> dense back-to-back dependencies (forwarding, load-use)
  - x28 = RAM base (never overwritten), 64 words pre-initialized (no X loads)
  - ALU R/I, LUI/AUIPC, loads/stores (all sizes, aligned), forward branches,
    jal / jalr skipping 1-3 instructions
  - no self-check : the commit trace vs the ISS is the check
usage: gen_rand_test.py seed n_inst out.S
"""
import random, sys

seed, n, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
R = random.Random(seed)
REGS = [f'x{i}' for i in range(1, 13)]
L = [f'# t_rand seed={seed} n={n} (generated by TOOLS/gen_rand_test.py)',
     '        .section .text.init', '        .globl _start', '_start:',
     '        li      x28, 0x10000000']
for i in range(64):
        L.append(f'        li      x1, {R.getrandbits(32):#010x}')
        L.append(f'        sw      x1, {4*i}(x28)')
for r in REGS:
        L.append(f'        li      {r}, {R.getrandbits(32):#010x}')

lab = 0
pending = []                    # (remaining, label)


def rr(): return R.choice(REGS)


def body():
        global lab
        k = R.random()
        if k < 0.30:
                op = R.choice(['add', 'sub', 'sll', 'slt', 'sltu', 'xor', 'srl', 'sra', 'or', 'and'])
                return [f'        {op:<7} {rr()}, {rr()}, {rr()}']
        if k < 0.50:
                op = R.choice(['addi', 'slti', 'sltiu', 'xori', 'ori', 'andi'])
                return [f'        {op:<7} {rr()}, {rr()}, {R.randint(-2048, 2047)}']
        if k < 0.57:
                op = R.choice(['slli', 'srli', 'srai'])
                return [f'        {op:<7} {rr()}, {rr()}, {R.randint(0, 31)}']
        if k < 0.60:
                return [f'        {R.choice(["lui", "auipc"]):<7} {rr()}, {R.getrandbits(20):#x}']
        if k < 0.75:
                op, sz = R.choice([('lw', 4), ('lh', 2), ('lhu', 2), ('lb', 1), ('lbu', 1)])
                return [f'        {op:<7} {rr()}, {R.randrange(0, 256, sz)}(x28)']
        if k < 0.85:
                op, sz = R.choice([('sw', 4), ('sh', 2), ('sb', 1)])
                return [f'        {op:<7} {rr()}, {R.randrange(0, 256, sz)}(x28)']
        lab += 1
        skip = R.randint(1, 3)
        name = f'L{lab}'
        pending.append([skip, name])
        if k < 0.95:
                op = R.choice(['beq', 'bne', 'blt', 'bge', 'bltu', 'bgeu'])
                return [f'        {op:<7} {rr()}, {rr()}, {name}']
        if k < 0.98:
                return [f'        jal     {rr()}, {name}']
        r = rr()
        return [f'        la      x29, {name}', f'        jalr    {r}, 0(x29)']


i = 0
while i < n:
        for line in body():
                L.append(line)
        i += 1
        for p in pending:
                p[0] -= 1
        for p in [p for p in pending if p[0] <= 0]:
                L.append(f'{p[1]}:')
                pending.remove(p)
for p in pending:
        L.append(f'{p[1]}:')
L += ['        li      x31, 0x40003000', '        li      x30, 1', '        sw      x30, 0(x31)', '1:      j       1b']
open(out, 'w').write('\n'.join(L) + '\n')
