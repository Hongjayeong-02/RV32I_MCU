HERE = os.path.dirname(os.path.abspath(__file__))
T_O  = os.path.join(HERE, 'build', 'insts.o')
os.makedirs(os.path.join(HERE, 'build'), exist_ok=True)
_S = os.path.join(HERE, 'build', 'insts.S')
with open(_S, 'w') as _f:
    _f.write('.option norvc\n.text\n' + open(os.path.join(HERE, 'insts.txt')).read())
subprocess.run(['riscv64-unknown-elf-as', '-march=rv32i_zicsr', '-mabi=ilp32', _S, '-o', T_O], check=True)
asm = [l.strip() for l in open(os.path.join(HERE,'insts.txt')) if l.strip()]
dump = subprocess.run(['riscv64-unknown-elf-objdump','-d',T_O],capture_output=True,text=True).stdout
words = [int(m.group(1),16) for m in re.finditer(r'^\s+[0-9a-f]+:\s+([0-9a-f]{8})', dump, re.M)]
W = dict(zip(asm, words))
I,S,B,U,J,Z = range(6)
cases = [
 ('lui x5, 0x12345',      U, 0x12345000),
 ('auipc x6, 0xfffff',    U, 0xfffff000),
 ('jal x1, .+2048',       J, 2048),
 ('jal x0, .-4',          J, -4),
 ('jal x1, .+1048574',    J, 1048574),
 ('jal x1, .-1048576',    J, -1048576),
 ('jalr x1, 12(x5)',      I, 12),
 ('beq x1, x2, .+16',     B, 16),
 ('bne x3, x4, .-8',      B, -8),
 ('beq x1, x2, .-4096',   B, -4096),
 ('bne x1, x2, .+4094',   B, 4094),
 ('lb x5, -1(x6)',        I, -1),
 ('addi x5, x6, -2048',   I, -2048),
 ('addi x5, x6, 2047',    I, 2047),
 ('xori x5, x6, -1',      I, -1),
 ('sb x5, -3(x6)',        S, -3),
 ('sw x5, 8(x6)',         S, 8),
 ('sw x5, 2047(x6)',      S, 2047),
 ('sw x5, -2048(x6)',     S, -2048),
 ('csrrwi x5, mscratch, 3', Z, 3),
 ('csrrsi x5, mstatus, 8',  Z, 8),
]
with open(os.path.join(HERE,'..','proj2_make','TOP','SIM','TESTBENCH','imm_vectors.vh'),'w') as f:
    f.write('// generated by TOOLS/gen_imm_vectors.py\n')
    for a,t,v in cases:
        f.write(f'        chk_vec(32\'h{W[a]:08x}, 3\'d{t}, 32\'h{v & 0xffffffff:08x}, "{a}");\n')
print(len(cases),'imm vectors')
