#!/usr/bin/env python3
"""
build_prog.py : test program -> files the RTL TB needs (spec 9, 12)

  TOOLS/tests/<name>.S  (assembly, own _start)     or
  TOOLS/tests/<name>.c  (C, linked with sw/crt0.S)
        -> proj2_make/TOP/SIM/PROG/<name>/
             rv32_rom.v      case ROM, 2 read ports (spec 7)
             expected.hex    ISS commit records for $readmemh (+ end marker)
             expected.trace  same, human readable (diff with the RTL trace)
             prog.dump       objdump -d

usage: build_prog.py name [name ...]          own tests (TOOLS/tests)
       build_prog.py --riscv-tests [ui|mi ...] riscv-tests rv32ui / rv32mi, ported with
                                                riscv_tests_env/riscv_test.h -> SIM/PROG/rv32ui_<t>/
(needs riscv64-unknown-elf-gcc ; --riscv-tests also needs git access to GitHub)
"""
import os, sys, subprocess, shutil

HERE  = os.path.dirname(os.path.abspath(__file__))
SW    = os.path.join(HERE, 'sw')
TESTS = os.path.join(HERE, 'tests')
OUT   = os.path.join(HERE, '..', 'proj2_make', 'TOP', 'SIM', 'PROG')
BUILD = os.path.join(HERE, 'build')
GCC   = 'riscv64-unknown-elf-gcc'
REPLAY_TAG = 'REPLAY-TEST'            # put this word in a test source : SoC replay mode only
BASE  = ['-march=rv32i_zicsr', '-mabi=ilp32', '-nostdlib', '-nostartfiles',
         '-ffreestanding', '-T', os.path.join(SW, 'link.ld')]
FLAGS = BASE + ['-I', SW]


class BuildError(Exception):
        pass


def run(cmd, quiet=False):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
                if quiet:
                        raise BuildError(r.stderr.strip().splitlines()[-2] if r.stderr else 'build error')
                print(' '.join(cmd)); print(r.stdout, r.stderr)
                sys.exit(1)
        return r.stdout


def rom_v(words, name):
        L = []
        L.append('`timescale 1ns/1ps')
        L.append('// -----------------------------------------------------------------------------')
        L.append(f'// rv32_rom  (generated by TOOLS/build_prog.py from tests/{name})')
        L.append('//   4 KB case ROM, two combinational read ports (spec 7):')
        L.append('//     port A = instruction fetch (IF), port B = data load (MEM, .rodata)')
        L.append('//   unused words read 0.')
        L.append('// -----------------------------------------------------------------------------')
        L.append('module rv32_rom (')
        L.append('        input   wire    [11:0]  i_addrA,')
        L.append('        output  wire    [31:0]  o_dataA,')
        L.append('        input   wire    [11:0]  i_addrB,')
        L.append('        output  wire    [31:0]  o_dataB')
        L.append(');')
        L.append('')
        L.append('function [31:0] rom_word;')
        L.append('        input   [9:0]   a;')
        L.append('        begin')
        L.append('                case (a)')
        for i, w in enumerate(words):
                if w:
                        L.append(f"                        10'd{i:<4}: rom_word = 32'h{w:08x};")
        L.append("                        default : rom_word = 32'h00000000;")
        L.append('                endcase')
        L.append('        end')
        L.append('endfunction')
        L.append('')
        L.append('assign o_dataA = rom_word(i_addrA[11:2]);')
        L.append('assign o_dataB = rom_word(i_addrB[11:2]);')
        L.append('')
        L.append('endmodule')
        return '\n'.join(L) + '\n'


def build(name, src=None, extra=None, must_pass=True):
        if src is None:
                for ext in ('.S', '.c'):
                        p = os.path.join(TESTS, name + ext)
                        if os.path.exists(p):
                                src = p
        if src is None:
                print(f'no tests/{name}.S or .c'); sys.exit(1)
        b = os.path.join(BUILD, name); os.makedirs(b, exist_ok=True)
        elf = os.path.join(b, 'prog.elf')
        if src.endswith('.c'):
                run([GCC] + FLAGS + ['-O2', os.path.join(SW, 'crt0.S'), os.path.join(SW, 'trap.S'), src, '-lgcc', '-o', elf])
        elif extra:
                try:
                        run([GCC] + BASE + extra + [src, '-o', elf], quiet=True)
                except BuildError as e:
                        print(f'{name:<20} BUILD FAIL : {e}')
                        return 'BUILD'
        else:
                run([GCC] + FLAGS + [src, '-o', elf])
        binf = os.path.join(b, 'rom.bin')
        run(['riscv64-unknown-elf-objcopy', '-O', 'binary', '-j', '.text', '-j', '.rodata', '-j', '.data', elf, binf])
        rom = open(binf, 'rb').read()
        if len(rom) > 4096:
                print(f'{name}: ROM image {len(rom)} B > 4 KB'); sys.exit(1)
        rom += bytes((-len(rom)) % 4)
        words = [int.from_bytes(rom[i:i + 4], 'little') for i in range(0, len(rom), 4)]

        o = os.path.join(OUT, name); os.makedirs(o, exist_ok=True)
        shutil.copy(binf, os.path.join(o, 'rom.bin'))
        if REPLAY_TAG in open(src).read():
                # peripheral / asynchronous test : no expected.hex, checked by TOOLS/check_replay.py
                for f in ('expected.hex', 'expected.trace'):
                        if os.path.exists(os.path.join(o, f)):
                                os.remove(os.path.join(o, f))
                open(os.path.join(o, 'rv32_rom.v'), 'w').write(rom_v(words, os.path.basename(src)))
                open(os.path.join(o, 'prog.dump'), 'w').write(run(['riscv64-unknown-elf-objdump', '-d', '-M', 'no-aliases', elf]))
                print(f'{name:<20} ROM {len(rom):5d} B | replay test (SoC only)')
                return True
        r = subprocess.run([sys.executable, os.path.join(HERE, 'rv32_iss.py'), binf, o], capture_output=True, text=True)
        print(f'{name:<20} ROM {len(rom):5d} B | {r.stdout.strip()}')
        if r.returncode:
                shutil.rmtree(o, ignore_errors=True)
                if must_pass:
                        sys.exit(1)
                return False
        with open(os.path.join(o, 'expected.hex'), 'a') as f:
                f.write('ffffffff\n' * 8)            # end marker
        open(os.path.join(o, 'rv32_rom.v'), 'w').write(rom_v(words, os.path.basename(src)))
        open(os.path.join(o, 'prog.dump'), 'w').write(run(['riscv64-unknown-elf-objdump', '-d', '-M', 'no-aliases', elf]))
        return True


# riscv-tests that need features this core does not have (spec 4)
RT_SKIP = {
        'fence_i': 'Zifencei not implemented (FENCE.I is illegal)',
        'ma_data': 'misaligned data access traps (no HW support)',
        'breakpoint': 'no trigger module (tselect/tdata)',
        'pmpaddr': 'no PMP',
        'zicntr': 'no user counters (cycle/time/instret 0xC0x)',
}


def riscv_tests(suites):
        rt = os.path.join(BUILD, 'riscv-tests')
        if not os.path.isdir(rt):
                run(['git', 'clone', '-q', '--depth', '1', 'https://github.com/riscv-software-src/riscv-tests.git', rt])
        env = os.path.join(HERE, 'riscv_tests_env')
        res = []
        for su in suites:
                d = os.path.join(rt, 'isa', f'rv32{su}')
                for f in sorted(os.listdir(d)):
                        if not f.endswith('.S'):
                                continue
                        t = f[:-2]
                        if t in RT_SKIP:
                                res.append((f'rv32{su}_{t}', 'SKIP ' + RT_SKIP[t]))
                                continue
                        ok = build(f'rv32{su}_{t}', os.path.join(d, f),
                                   ['-I', env, '-I', os.path.join(rt, 'isa', 'macros', 'scalar')], must_pass=False)
                        res.append((f'rv32{su}_{t}', {True: 'PASS', False: 'FAIL', 'BUILD': 'SKIP image does not fit 4 KB ROM / link error'}[ok]))
        print()
        for n, r in res:
                if r != 'PASS':
                        print(f'{n:<22} {r}')
        print(f"riscv-tests on ISS : {sum(r == 'PASS' for _, r in res)} PASS, "
              f"{sum(r == 'FAIL' for _, r in res)} FAIL, {sum(r.startswith('SKIP') for _, r in res)} SKIP")


if __name__ == '__main__':
        if sys.argv[1:2] == ['--riscv-tests']:
                riscv_tests(sys.argv[2:] or ['ui', 'mi'])
        else:
                names = sys.argv[1:] or sorted({os.path.splitext(f)[0] for f in os.listdir(TESTS)})
                for n in names:
                        build(n)
