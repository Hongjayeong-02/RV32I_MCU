#!/bin/bash
# make_pdk_setup.sh : build APR/scripts/pdk_setup.tcl (git-ignored) from the UART V4
# Innovus scripts already on this server, so no PDK path is ever written in PROJ2.
#   cd APR/scripts ; bash make_pdk_setup.sh [path to UART V4 pnr scripts dir]
cd "$(dirname "$0")" || exit 1
SRC=${1:-$(dirname "$(find ~/UART_V4 ~/UART_repo -name uart_v4_apb.mmmc.view 2>/dev/null | xargs grep -L '<PDK>' | head -1)")}
if [ ! -f "$SRC/uart_v4_apb.mmmc.view" ] || grep -q '<PDK>' "$SRC/uart_v4_apb.mmmc.view"; then
  echo "ERROR: UART V4 mmmc with real PDK paths not found (give the scripts dir as argument)"; exit 1
fi
echo "INFO: PDK lines taken from $SRC"
{
  echo "# generated by make_pdk_setup.sh from $SRC  -- DO NOT COMMIT"
  grep -E '^set (G?PDK)[A-Za-z_0-9]* ' "$SRC/0_InitDesign.tcl"
  # init_lef_file statement (may span lines with \)
  awk '/^set init_lef_file/{p=1} p{print} p && !/\\$/{exit}' "$SRC/0_InitDesign.tcl"
  # RC corners and library sets, unchanged
  grep -E '^(create_rc_corner|create_library_set)' "$SRC/uart_v4_apb.mmmc.view" | sed 's/^/set_pdk_line {/; s/$/}/'
} > pdk_setup.tcl
echo "INFO: wrote pdk_setup.tcl"; cat pdk_setup.tcl | sed 's#/[^ ]*/#.../#g'
